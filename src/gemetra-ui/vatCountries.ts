/** Parse leading numeric % from refundRate for sorting (e.g. "Up to 20% net" → 20). */
export function parseRefundRatePercent(rate: string): number {
  const paren = rate.match(/\(~?(\d+(?:\.\d+)?)\s*%\)/);
  if (paren) return parseFloat(paren[1]);
  const upTo = rate.match(/(?:up to|from)\s*~?(\d+(?:\.\d+)?)\s*%/i);
  if (upTo) return parseFloat(upTo[1]);
  const match = rate.match(/~?(\d+(?:\.\d+)?)\s*%/);
  return match ? parseFloat(match[1]) : 0;
}

/** Compact label for cards (e.g. "Up to 20% net" → "20%"). */
export function netRefundShort(rate: string): string {
  const pct = parseRefundRatePercent(rate);
  if (pct > 0) return `${pct}%`;
  return rate.replace(/^(Up to |From |~)/, '').replace(/ net$/, '').trim();
}
