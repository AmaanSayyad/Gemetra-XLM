/** Regional proxy when Atlys has no asset (only XI → GB). */
const MEDIA_PROXY: Record<string, string> = {
  XI: 'GB',
};

export function countryMediaCode(code: string): string {
  if (MEDIA_PROXY[code]) return MEDIA_PROXY[code];
  if (ATLYS_MEDIA_CODES.has(code)) return code;
  return 'FR';
}

/** Parse statutory VAT/GST % from vatRate (e.g. "20%" or "10–20% VAT" → 20). */
export function parseVatRatePercent(vatRate: string): number {
  const range = vatRate.match(/(\d+(?:\.\d+)?)\s*[–-]\s*(\d+(?:\.\d+)?)\s*%/);
  if (range) return Math.max(parseFloat(range[1]), parseFloat(range[2]));
  const match = vatRate.match(/(\d+(?:\.\d+)?)\s*%/);
  return match ? parseFloat(match[1]) : 0;
}

export function getCountryByCode(code: string): VatCountry | undefined {
  return VAT_COUNTRIES.find((c) => c.code === code);
}

